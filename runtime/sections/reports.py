REPORTS = "/reports/2021-06-30/reports"
REPORT = "/reports/2021-06-30/reports/{reportId}"
DOCUMENT = "/reports/2021-06-30/documents/{reportDocumentId}"

TAB_SEPARATED = "text/tab-separated-values"


