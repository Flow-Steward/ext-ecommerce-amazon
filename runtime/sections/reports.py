_FILENAME_SAFE = re.compile(r"[^A-Za-z0-9._-]+")


def _report_type(name: Any) -> ReportType:
    row = REPORT_TYPES.get(str(name))
    if row is None:  # pragma: no cover - the input enum already refuses it
        raise ExtensionError(errors.INVALID_PAYLOAD, "That report type is not supported")
    return row


def normalize_report(raw: Any) -> dict[str, Any]:
    report_type = dig(raw, "reportType")
    known = REPORT_TYPES.get(str(report_type))
    return {
        "report_id": dig(raw, "reportId"),
        "report_type": report_type,
        "processing_status": dig(raw, "processingStatus"),
        "marketplace_ids": as_list(dig(raw, "marketplaceIds")),
        "data_start_time": dig(raw, "dataStartTime"),
        "data_end_time": dig(raw, "dataEndTime"),
        "created_time": dig(raw, "createdTime"),
        "processing_start_time": dig(raw, "processingStartTime"),
        "processing_end_time": dig(raw, "processingEndTime"),
        "report_schedule_id": dig(raw, "reportScheduleId"),
        "report_document_id": dig(raw, "reportDocumentId"),
        "contains_pii": known.contains_pii if known is not None else None,
        "amazon": raw,
    }


def _search_reports(context: Context) -> dict[str, Any]:
    data = context.input
    for name in ("created_since", "created_until"):
        validation.timestamp(data.get(name), name)
    token = pagination.unwrap(context, API_VERSION)
    if token is not None:
        # Amazon: nextToken must be the only parameter; the wrapped token already
        # carries proof that the filters are those of the first page.
        query: dict[str, Any] = {"nextToken": token}
    else:
        query = {
            "reportTypes": data["report_types"],
            "processingStatuses": data.get("processing_statuses"),
            "marketplaceIds": [context.connection.marketplace_id],
            "pageSize": data.get("page_size"),
            "createdSince": data.get("created_since"),
            "createdUntil": data.get("created_until"),
        }
    response = context.transport.call(
        "GET", REPORTS, query=query, mutating=False, purpose="Amazon search reports"
    )
    reports = as_list(dig(response.body, "reports"))
    return {
        "reports": [normalize_report(item) for item in reports],
        "count": len(reports),
        "next_token": pagination.wrap(context, API_VERSION, dig(response.body, "nextToken")),
    }


def _create_report(context: Context) -> dict[str, Any]:
    """createReport for a requestable report type.

    Requesting a report only asks Amazon to compile a file from the seller's
    existing data; it changes no listing, order, price or stock, and Amazon
    keeps the file for a limited time on its own. It is therefore not an
    external effect on the seller's data (``mutating=False``), and a repeat only
    produces a second copy of the same report.
    """
    data = context.input
    row = _report_type(data["report_type"])
    if not row.creatable:
        raise ExtensionError(
            errors.INVALID_PAYLOAD,
            f"{row.name} cannot be requested: Amazon generates it on its own schedule. "
            "Find it with search_reports and fetch it with download_report.",
        )
    start = validation.timestamp(data.get("data_start_time"), "data_start_time")
    end = validation.timestamp(data.get("data_end_time"), "data_end_time")
    body: dict[str, Any] = {
        "reportType": row.name,
        "marketplaceIds": [context.connection.marketplace_id],
    }
    if start is not None:
        body["dataStartTime"] = start
    if end is not None:
        body["dataEndTime"] = end
    response = context.transport.call(
        "POST", REPORTS, body=body, mutating=False, purpose="Amazon create report"
    )
    report_id = dig(response.body, "reportId")
    if not isinstance(report_id, str) or not report_id:
        raise ExtensionError(errors.UPSTREAM_FAILURE, "Amazon returned no report ID")
    return {"report_id": report_id, "report_type": row.name, "contains_pii": row.contains_pii}


def _read_report(context: Context, report_id: str) -> dict[str, Any]:
    response = context.transport.call(
        "GET", REPORT, path={"reportId": report_id}, mutating=False, purpose="Amazon get report"
    )
    if not isinstance(response.body, Mapping) or not response.body.get("reportId"):
        raise ExtensionError(errors.NOT_FOUND, "Amazon returned no report for that ID")
    return normalize_report(response.body)


def _get_report(context: Context) -> dict[str, Any]:
    report = _read_report(context, str(context.input["report_id"]))
    return {
        "report": report,
        "processing_status": report["processing_status"],
        "report_document_id": report["report_document_id"],
    }


def _download_report(context: Context) -> dict[str, Any]:
    report_id = str(context.input["report_id"])
    report = _read_report(context, report_id)
    report_type = report["report_type"]
    if report_type not in REPORT_TYPES:
        raise ExtensionError(
            errors.INVALID_PAYLOAD, "That report's type is not supported by this extension"
        )
    if report["processing_status"] != "DONE" or not report["report_document_id"]:
        raise ExtensionError(
            errors.DOCUMENT_UNAVAILABLE,
            f"The report is {report['processing_status'] or 'not ready'}; download it once its status is DONE",
        )
    row = _report_type(report_type)
    document_id = str(report["report_document_id"])
    response = context.transport.call(
        "GET",
        DOCUMENT,
        path={"reportDocumentId": document_id},
        mutating=False,
        purpose="Amazon get report document",
    )
    content, compressed = documents.fetch_document(
        context,
        response.body,
        max_download_bytes=MAX_REPORT_DOWNLOAD_BYTES,
        max_content_bytes=MAX_REPORT_CONTENT_BYTES,
        purpose="Amazon report download",
    )
    written = documents.write_artifact(context, REPORT_OUTPUT, content)
    name_part = _FILENAME_SAFE.sub("_", report_id)[:80]
    return {
        "artifact_handle": written["artifact_handle"],
        "size_bytes": written["size_bytes"],
        "sha256": written["sha256"],
        "content_type": row.content_type,
        "filename": f"{row.name}-{name_part}.tsv",
        "report_type": row.name,
        "report_id": report_id,
        "report_document_id": document_id,
        "was_compressed": compressed,
        "contains_pii": row.contains_pii,
    }


